/**
 * "PoolDN" wordmark. Set in the app font rather than traced letterforms:
 * the previous mark was hand-drawn SVG paths spelling the old name, and glyph
 * paths can't be re-lettered. Text also stays crisp at any size and gives the
 * logo link a real accessible name (the BallMark beside it is aria-hidden).
 */
export function Wordmark({ className }: { className?: string }) {
  return (
    <span
      className={cn(
        "select-none whitespace-nowrap font-extrabold leading-none tracking-tight",
        className,
      )}
    >
      PoolDN
    </span>
  );
}
